function corsHeaders(origin) {
  // يعكس أي origin (يضمن عمل المساعد من أي رابط: GitHub Pages / الدومين / Coolify).
  // يمكن لاحقًا التقييد بإعادة استخدام ALLOWED_ORIGINS لو رغبت.
  const allow = origin || "*";
  return {
    "Access-Control-Allow-Origin": allow,
    "Vary": "Origin",
    "Access-Control-Allow-Methods": "POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type",
    "Access-Control-Max-Age": "86400",
  };
}

export default {
  async fetch(request, env) {
    const origin = request.headers.get("Origin") || "";

    if (request.method === "OPTIONS") {
      return new Response(null, { headers: corsHeaders(origin) });
    }
    if (request.method !== "POST") {
      return json({ error: "Method not allowed" }, 405, origin);
    }
    if (!env.GEMINI_API_KEY) {
      return json({ error: "Server not configured" }, 500, origin);
    }

    let body;
    try { body = await request.json(); }
    catch { return json({ error: "Bad request" }, 400, origin); }

    const messages = Array.isArray(body.messages) ? body.messages : [];
    if (!messages.length) return json({ error: "No messages" }, 400, origin);

    // حوّل الرسائل لصيغة Gemini
    const contents = messages.slice(-16).map((m) => ({
      role: m.role === "assistant" ? "model" : "user",
      parts: [{ text: String(m.content || "").slice(0, 4000) }],
    }));

    const payload = {
      systemInstruction: { parts: [{ text: SYSTEM_PROMPT }] },
      contents,
      generationConfig: {
        temperature: 0.7,
        maxOutputTokens: 800,
        topP: 0.95,
      },
      safetySettings: [
        { category: "HARM_CATEGORY_HARASSMENT", threshold: "BLOCK_ONLY_HIGH" },
        { category: "HARM_CATEGORY_HATE_SPEECH", threshold: "BLOCK_ONLY_HIGH" },
      ],
    };

    const url = `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent?key=${env.GEMINI_API_KEY}`;

    let gResp;
    try {
      gResp = await fetch(url, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(payload),
      });
    } catch (e) {
      return json({ error: "Upstream error" }, 502, origin);
    }

    if (!gResp.ok) {
      const t = await gResp.text();
      return json({ error: "AI error", detail: t.slice(0, 200) }, 502, origin);
    }

    const data = await gResp.json();
    const reply =
      data?.candidates?.[0]?.content?.parts?.map((p) => p.text).join("") ||
      "عذرًا، صار خلل بسيط. جرّب مرة ثانية لو سمحت.";

    return json({ reply }, 200, origin);
  },
};

function json(obj, status, origin) {
  return new Response(JSON.stringify(obj), {
    status,
    headers: { "Content-Type": "application/json", ...corsHeaders(origin) },
  });
}
